const dictionaries: Record<Lang, Record<Key, string>> = { en, sv }

export type TFunction = (key: Key, vars?: Record<string, string | number>) => string

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = dictionaries[lang][key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function useT(): TFunction {
  const lang = useAppState((s) => s.settings.language)
  return useCallback((key, vars) => translate(lang, key, vars), [lang])
}
