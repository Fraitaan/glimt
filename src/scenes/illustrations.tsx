export function Illustration({ name, size = 200 }: { name: IllustrationKey; size?: number }) {
  const els = D[name] ?? D.lightbulb
  let i = 0
  return (
    <svg
      viewBox="0 0 200 200"
      width={size}
      height={size}
      className="illustration"
      fill="none"
      stroke="currentColor"
      strokeWidth={3}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
    >
      {els.map((el, k) => {
        const delay = 0.15 + i++ * 0.09
        const draw = {
          initial: { pathLength: 0, opacity: 0 },
          animate: { pathLength: 1, opacity: 1 },
          transition: { pathLength: { duration: 0.9, delay, ease: 'easeInOut' as const }, opacity: { duration: 0.2, delay } },
        }
        const pop = {
          initial: { opacity: 0, scale: 0.4 },
          animate: { opacity: 1, scale: 1 },
          transition: { duration: 0.5, delay: delay + 0.4, ease: [0.2, 0.9, 0.3, 1.3] as const },
        }
        switch (el[0]) {
          case 'p':
            // After drawing, a spark of light keeps travelling along the line.
            return (
              <Fragment key={k}>
                <motion.path d={el[1]} {...draw} />
                <path d={el[1]} className="flow" pathLength={100} style={{ animationDelay: `${delay + 1}s, ${delay + 1}s` }} />
              </Fragment>
            )
          case 'c':
            return (
              <Fragment key={k}>
                <motion.circle cx={el[1]} cy={el[2]} r={el[3]} {...draw} />
                <circle cx={el[1]} cy={el[2]} r={el[3]} className="flow" pathLength={100} style={{ animationDelay: `${delay + 1}s, ${delay + 1}s` }} />
              </Fragment>
            )
          case 'f':
            return (
              <motion.path
                key={k}
                d={el[1]}
                fill="currentColor"
                stroke="none"
                className="breathe"
                style={{ animationDelay: `${delay + 1.2}s` }}
                initial={{ opacity: 0 }}
                animate={{ opacity: 0.16 }}
                transition={{ duration: 0.8, delay: delay + 0.3 }}
              />
            )
          case 'd':
            return (
              <motion.circle
                key={k}
                cx={el[1]}
                cy={el[2]}
                r={el[3]}
                fill="currentColor"
                stroke="none"
                className="pulse"
                style={{ transformOrigin: `${el[1]}px ${el[2]}px`, animationDelay: `${delay + 1}s` }}
                {...pop}
              />
            )
        }
      })}
    </svg>
  )
}
